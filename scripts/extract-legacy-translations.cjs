const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const root = path.resolve(__dirname, "..");
const sourcePath = path.join(root, "js", "content.legacy.js");
const outputPath = path.join(root, "js", "translations-base.js");
const source = fs.readFileSync(sourcePath, "utf8");

const startMarker = "const allData = ";
const endMarker = "\n\nlet MutationObserver";
const start = source.indexOf(startMarker);
const end = source.indexOf(endMarker, start);
if (start < 0 || end < 0) throw new Error("Unable to locate legacy translation array");

const expression = source.slice(start + startMarker.length, end).replace(/;\s*$/, "");
const entries = vm.runInNewContext(`(${expression})`, Object.create(null), { timeout: 1000 });
if (!Array.isArray(entries)) throw new Error("Legacy translations did not evaluate to an array");

const seen = new Map();
const conflicts = [];
for (const entry of entries) {
  if (!Array.isArray(entry) || entry.length !== 2 || entry.some(value => typeof value !== "string")) {
    throw new Error(`Invalid legacy entry: ${JSON.stringify(entry)}`);
  }
  const [sourceText, translatedText] = entry;
  if (seen.has(sourceText) && seen.get(sourceText) !== translatedText) {
    conflicts.push({ sourceText, first: seen.get(sourceText), next: translatedText });
  }
  seen.set(sourceText, translatedText);
}

const uniqueEntries = [...seen.entries()];
const banner = [
  "// Generated from LinearCN 1.2.0 by scripts/extract-legacy-translations.cjs.",
  "// Original extension license: GNU GPL v3. See ../LICENSE.",
  "// Do not edit this file by hand; put maintained additions in translations-enhanced.js.",
  "",
].join("\n");
const body = `globalThis.LinearCNBaseEntries = ${JSON.stringify(uniqueEntries, null, 2)};\n`;
fs.writeFileSync(outputPath, banner + body, "utf8");

process.stdout.write(JSON.stringify({
  inputEntries: entries.length,
  uniqueEntries: uniqueEntries.length,
  duplicateEntries: entries.length - uniqueEntries.length,
  conflicts,
  outputPath,
}, null, 2));
